// Falls back to the colored icons in src/data/icons.json (email, whatsapp, ...).
export default function SocialIcon({ name, size = 20 }: { name: string; size?: number }) {
  const key = name.toLowerCase();
  const d = paths[key];
  if (!d) {
    const svg = (icons as Record<string, string>)[key];
    return svg ? <span className="svg-fit" style={{ width: size, height: size }} dangerouslySetInnerHTML={{ __html: svg }} /> : null;
  }
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
      <path d={d} />
    </svg>
  );
}
